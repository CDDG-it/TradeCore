#!/usr/bin/env node
/**
 * Writes src/app/(app)/opaque-surfaces.css: every see-through surface class in
 * the app (bg-card/60, bg-background/40, a rounded panel in bg-primary/[0.05])
 * gets the same colour, pre-mixed onto the surface it is designed to sit on,
 * so it looks the same but is solid. Without this the animated backdrop shows
 * through every card.
 *
 *   bg-card/N        mixed onto the page background (cards sit on the page)
 *   bg-background/N  mixed onto the card (tiles sit inside cards)
 *   tints/N          mixed onto the card, only on rounded panels (xl, 2xl, 3xl):
 *                    pills, bars and icons stay as they are
 *
 * Elements that change background on hover are left alone, so the hover still
 * works. Runs before every build (npm "prebuild"), so new classes are picked up.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "src");
const OUT = path.join(SRC, "app", "(app)", "opaque-surfaces.css");
const TINTS = ["primary", "ice", "success", "destructive", "warning", "win", "loss", "be", "muted", "secondary", "gold", "accent"];
const TOKEN = new RegExp(`(?<=^|[\\s"'\`])bg-(card|background|${TINTS.join("|")})/(\\d+|\\[\\d*\\.?\\d+%?\\])(?=$|[\\s"'\`])`, "g");

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (/\.(tsx|ts)$/.test(e.name)) out.push(p);
  }
  return out;
}

/** "60" -> 60, "[0.05]" -> 5, "[12%]" -> 12 */
function percent(alpha) {
  if (!alpha.startsWith("[")) return Number(alpha);
  const v = alpha.slice(1, -1);
  return v.endsWith("%") ? Number(v.slice(0, -1)) : Number(v) * 100;
}

const escape = (cls) => cls.replace(/[/[\].%]/g, (c) => `\\${c}`);
const round = (n) => Math.round(n * 100) / 100;

const found = new Map();
for (const file of walk(SRC)) {
  for (const m of fs.readFileSync(file, "utf8").matchAll(TOKEN)) found.set(m[0], { color: m[1], pct: round(percent(m[2])) });
}

const NOT_HOVER = ':not([class*="hover:bg-"])';
const rules = [...found.entries()]
  .sort(([a], [b]) => a.localeCompare(b, "en", { numeric: true }))
  .map(([cls, { color, pct }]) => {
    const sel = `.${escape(cls)}${NOT_HOVER}`;
    if (color === "card") return `.app-surface ${sel} { background-color: color-mix(in oklab, var(--color-card) ${pct}%, var(--color-background)); }`;
    if (color === "background") return `.app-surface ${sel} { background-color: color-mix(in oklab, var(--color-background) ${pct}%, var(--color-card)); }`;
    return `.app-surface :is(.rounded-xl, .rounded-2xl, .rounded-3xl)${sel} { background-color: color-mix(in oklab, var(--color-${color}) ${pct}%, var(--color-card)); }`;
  });

const css = `/* Generated by scripts/gen-opaque-surfaces.mjs: do not edit by hand. */
/* Solid versions of the app's see-through surfaces, so the backdrop never shows through a card. */
${rules.join("\n")}
`;
const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
if (prev !== css) fs.writeFileSync(OUT, css);
console.log(`opaque-surfaces.css: ${rules.length} rules${prev === css ? " (unchanged)" : ""}`);
